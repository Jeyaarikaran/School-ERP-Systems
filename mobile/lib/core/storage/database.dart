import 'dart:io';
import 'package:drift/drift.dart';
import 'package:drift/native.dart';
import 'package:path_provider/package_provider.dart';
import 'package:path/path.dart' as p;

part 'database.g.dart'; // Will be generated by build_runner

/// SyncQueue table for offline-first architecture.
/// All mutations (like taking attendance) are written here first.
class SyncQueue extends Table {
  IntColumn get id => integer().autoIncrement()();
  TextColumn get clientOpId => text().unique()();
  TextColumn get operationType => text()(); // e.g., 'ATTENDANCE_SYNC'
  TextColumn get payloadJson => text()(); // The JSON payload to send
  IntColumn get status => integer().withDefault(const Constant(0))(); // 0: pending, 1: syncing, 2: failed
  DateTimeColumn get createdAt => dateTime().withDefault(currentDateAndTime)();
}

/// Offline cache for class rosters (so teachers can see students offline)
class RosterCache extends Table {
  TextColumn get studentId => text()();
  TextColumn get sectionId => text()();
  TextColumn get fullName => text()();
  IntColumn get rollNo => integer()();
  DateTimeColumn get fetchedAt => dateTime().withDefault(currentDateAndTime)();

  @override
  Set<Column> get primaryKey => {studentId, sectionId};
}

/// Local attendance drafts before they are sent to the SyncQueue
class AttendanceDrafts extends Table {
  TextColumn get studentId => text()();
  TextColumn get sectionId => text()();
  DateTimeColumn get date => dateTime()();
  TextColumn get status => text()(); // 'present', 'absent', etc.
  
  @override
  Set<Column> get primaryKey => {studentId, sectionId, date};
}

@DriftDatabase(tables: [SyncQueue, RosterCache, AttendanceDrafts])
class AppDatabase extends _$AppDatabase {
  AppDatabase() : super(_openConnection());

  @override
  int get schemaVersion => 1;

  // Example mutation: queueing an operation while offline
  Future<int> queueOperation(SyncQueueCompanion operation) {
    return into(syncQueue).insert(operation);
  }

  // Fetch cached roster for a section
  Future<List<RosterCacheData>> getRosterForSection(String sectionId) {
    return (select(rosterCache)..where((t) => t.sectionId.equals(sectionId))
      ..orderBy([(t) => OrderingTerm(expression: t.rollNo)])).get();
  }

  // Save a draft attendance record locally
  Future<void> saveAttendanceDraft(AttendanceDraftsCompanion draft) {
    return into(attendanceDrafts).insertOnConflictUpdate(draft);
  }
}

LazyDatabase _openConnection() {
  return LazyDatabase(() async {
    final dbFolder = await getApplicationDocumentsDirectory();
    final file = File(p.join(dbFolder.path, 'educore.sqlite'));
    return NativeDatabase.createInBackground(file);
  });
}
